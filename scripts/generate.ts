// Writes one module per icon to src/icons (12px and 20px icons go in
// src/icons/12 and src/icons/20), the src/index.ts barrel, and src/catalog.ts,
// which lists every icon by name for the tests and preview.
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { type Icon, readIcons } from "./read-icons";

const SRC_DIR = join(import.meta.dirname, "..", "src");
const OUT_DIR = join(SRC_DIR, "icons");

const camelCase = (attribute: string) =>
  attribute.replace(/-([a-z])/g, (_, letter: string) => letter.toUpperCase());

function iconModule(icon: Icon): string {
  const node = icon.shapes.map(({ tag, attributes }) => [
    tag,
    Object.fromEntries(
      Object.entries(attributes).map(([key, value]) => [camelCase(key), value]),
    ),
  ]);
  const root = icon.size === 16 ? ".." : "../..";
  const size = icon.size === 16 ? "" : `, ${icon.size}`;
  return [
    `// Generated from icons/${icon.path}.svg by scripts/generate.ts.`,
    `import type { ReactElement } from "react";`,
    `import { type IconNode, type IconProps, renderIcon } from "${root}/render-icon";`,
    "",
    `const node: IconNode = ${JSON.stringify(node)};`,
    "",
    `export function ${icon.name}(props: IconProps): ReactElement {`,
    `  return renderIcon(${JSON.stringify(icon.name)}, node, props${size});`,
    "}",
    "",
  ].join("\n");
}

const icons = readIcons();
const seen = new Map<string, string>();
for (const icon of icons) {
  const other = seen.get(icon.name);
  if (other) {
    throw new Error(
      `icons/${icon.path}.svg and icons/${other}.svg both become ${icon.name}`,
    );
  }
  seen.set(icon.name, icon.path);
}
const imports = icons.map(
  (icon) => `import { ${icon.name} } from "./icons/${icon.path}";`,
);

rmSync(OUT_DIR, { recursive: true, force: true });
for (const icon of icons) {
  const out = join(OUT_DIR, `${icon.path}.ts`);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, iconModule(icon));
}
writeFileSync(
  join(SRC_DIR, "index.ts"),
  [
    "// Generated by scripts/generate.ts.",
    `export * from "./render-icon";`,
    ...icons.map(
      (icon) => `export { ${icon.name} } from "./icons/${icon.path}";`,
    ),
    "",
  ].join("\n"),
);
writeFileSync(
  join(SRC_DIR, "catalog.ts"),
  [
    "// Generated by scripts/generate.ts. Not part of the published package.",
    `import type { IconComponent, IconSize } from "./render-icon";`,
    ...imports,
    "",
    "export const catalog: Record<string, { Icon: IconComponent; size: IconSize }> = {",
    ...icons.map(
      (icon) => `  ${icon.name}: { Icon: ${icon.name}, size: ${icon.size} },`,
    ),
    "};",
    "",
  ].join("\n"),
);
console.log(`Generated ${icons.length} icons`);
